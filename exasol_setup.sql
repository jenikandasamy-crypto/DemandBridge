CREATE SCHEMA IF NOT EXISTS DEMANDBRIDGE;
CREATE TABLE IF NOT EXISTS DEMANDBRIDGE.GROCERY_SALES (
 SALE_DATE DATE, STORE_ID VARCHAR(30), PRODUCT_ID VARCHAR(30), PRODUCT_NAME VARCHAR(100),
 CATEGORY VARCHAR(60), CHANNEL VARCHAR(30), CUSTOMER_ID VARCHAR(40), UNIT_PRICE DECIMAL(12,2),
 PROMOTION DECIMAL(1,0), STOCK_AVAILABLE DECIMAL(12,0), DEMAND_UNITS DECIMAL(12,2),
 UNITS_SOLD DECIMAL(12,2), LOST_SALES_UNITS DECIMAL(12,2));
SELECT CATEGORY, CHANNEL, SUM(UNITS_SOLD) AS TOTAL_UNITS
FROM DEMANDBRIDGE.GROCERY_SALES GROUP BY CATEGORY, CHANNEL ORDER BY TOTAL_UNITS DESC;
